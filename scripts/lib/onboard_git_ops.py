"""Diff preview and optional Git PR landing helpers for Layer 3 onboarding emission.

Keeps subprocess Git and GitHub CLI operations isolated from onboard_emitter.py so dry-run
previews stay pure and emit --pr degrades gracefully when gh or origin is unavailable.
"""
from __future__ import annotations

import difflib
import pathlib
import shutil
import subprocess
from typing import Any


def compute_unified_diffs(
    repo: pathlib.Path,
    writes: list[tuple[pathlib.Path, bytes, str]],
    unlinks: list[pathlib.Path],
) -> dict[str, str]:
    """Builds unified diffs for planned file writes and deletions without mutating disk."""
    diffs: dict[str, str] = {}
    for path, new_bytes, rel in writes:
        old_lines = path.read_text(encoding="utf-8", errors="replace").splitlines(keepends=True) if path.is_file() else []
        new_lines = new_bytes.decode("utf-8", errors="replace").splitlines(keepends=True)
        diff_text = "".join(
            difflib.unified_diff(
                old_lines,
                new_lines,
                fromfile=f"a/{rel}" if old_lines else "/dev/null",
                tofile=f"b/{rel}",
                n=3,
            )
        )
        if diff_text:
            diffs[rel] = diff_text
    for path in unlinks:
        rel = path.relative_to(repo).as_posix()
        old_lines = path.read_text(encoding="utf-8", errors="replace").splitlines(keepends=True) if path.is_file() else []
        diffs[rel] = "".join(difflib.unified_diff(old_lines, [], fromfile=f"a/{rel}", tofile="/dev/null", n=3))
    return diffs


def _run_git(repo: pathlib.Path, args: list[str]) -> subprocess.CompletedProcess[str]:
    """Executes one non-interactive Git command inside repo."""
    return subprocess.run(
        ["git", *args],
        cwd=str(repo),
        capture_output=True,
        text=True,
        check=False,
    )


def open_onboarding_pr(
    repo: pathlib.Path,
    slug: str,
    base_branch: str,
    emitted_files: list[str],
) -> dict[str, Any]:
    """Commits emitted Layer 3 files on a dedicated branch, pushes origin, and opens a GitHub PR."""
    branch = f"chore/factory-onboarding-{slug}"
    manual_cmds = [
        f"git checkout -b {branch}",
        "git add " + " ".join(emitted_files),
        f'git commit -m "chore(factory): onboard {slug} autonomous factory overlay"',
        f"git push -u origin {branch}",
        f'gh pr create --base {base_branch} --title "chore(factory): onboard {slug}" --body "Lands Layer 3 factory overlay generated by factory_onboard.py."',
    ]

    if _run_git(repo, ["rev-parse", "--is-inside-work-tree"]).returncode != 0:
        return {"status": "skipped", "reason": "not_a_git_repo", "branch": branch, "manual_commands": manual_cmds}

    cur_branch = _run_git(repo, ["rev-parse", "--abbrev-ref", "HEAD"]).stdout.strip()
    if cur_branch != branch:
        exists_local = _run_git(repo, ["show-ref", "--verify", "--quiet", f"refs/heads/{branch}"]).returncode == 0
        # Reuse existing onboarding branch without hard-resetting remote history; create new branch otherwise (M8).
        co = _run_git(repo, ["checkout", branch] if exists_local else ["checkout", "-b", branch])
        if co.returncode != 0:
            return {"status": "failed", "reason": co.stderr.strip(), "branch": branch, "manual_commands": manual_cmds}

    add_res = _run_git(repo, ["add", "--", *emitted_files])
    if add_res.returncode != 0:
        return {"status": "failed", "reason": add_res.stderr.strip(), "branch": branch, "manual_commands": manual_cmds}

    diff_cached = _run_git(repo, ["diff", "--cached", "--quiet"])
    if diff_cached.returncode == 0:
        return {"status": "unchanged", "branch": branch, "pr_url": None, "manual_commands": []}

    # Disable repo-local Git hooks during onboarding commit so unvetted .husky/pre-commit hooks never execute (M8).
    commit_res = _run_git(
        repo,
        ["-c", "core.hooksPath=/dev/null", "commit", "-m", f"chore(factory): onboard {slug} autonomous factory overlay"],
    )
    if commit_res.returncode != 0:
        return {"status": "failed", "reason": commit_res.stderr.strip(), "branch": branch, "manual_commands": manual_cmds}

    has_origin = _run_git(repo, ["remote", "get-url", "origin"]).returncode == 0
    if not has_origin:
        return {"status": "committed_local_only", "reason": "missing_origin_remote", "branch": branch, "manual_commands": manual_cmds[3:]}

    push_res = _run_git(repo, ["push", "-u", "origin", branch])
    if push_res.returncode != 0:
        return {"status": "committed_push_failed", "reason": push_res.stderr.strip(), "branch": branch, "manual_commands": manual_cmds[3:]}

    if not shutil.which("gh"):
        return {"status": "pushed_no_gh", "branch": branch, "pr_url": None, "manual_commands": manual_cmds[4:]}

    pr_res = subprocess.run(
        [
            "gh",
            "pr",
            "create",
            "--base",
            base_branch,
            "--head",
            branch,
            "--title",
            f"chore(factory): onboard {slug}",
            "--body",
            "Lands Layer 3 factory overlay (`.factory/`, `AGENTS.md`, conventions skill) generated by `factory_onboard.py`.",
        ],
        cwd=str(repo),
        capture_output=True,
        text=True,
        check=False,
    )
    if pr_res.returncode != 0:
        return {"status": "pushed_pr_failed", "reason": pr_res.stderr.strip(), "branch": branch, "manual_commands": manual_cmds[4:]}

    return {"status": "pr_opened", "branch": branch, "pr_url": pr_res.stdout.strip(), "manual_commands": []}
